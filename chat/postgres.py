"""PostgreSQL connection and migrations for the chat store."""

import psycopg
from psycopg.conninfo import conninfo_to_dict


class ChatConnection(psycopg.Connection):
    def execute(self, query, params=None):
        return super().execute(query.replace("?", "%s"), params)


def connect(database_url, migrations):
    options = conninfo_to_dict(database_url)
    options.setdefault("connect_timeout", "5")
    if "sslmode" not in options:
        options.setdefault("sslrootcert", "system")
        options["sslmode"] = "verify-full"
    conn = ChatConnection.connect(**options, autocommit=True, prepare_threshold=None)
    try:
        with conn.transaction():
            # Render can start a replacement instance while the old one is live.
            conn.execute("SELECT pg_advisory_xact_lock(1129070937)")
            conn.execute("CREATE SCHEMA IF NOT EXISTS claychat")
            conn.execute("REVOKE ALL ON SCHEMA claychat FROM PUBLIC")
            conn.execute("SET search_path TO claychat")
            conn.execute("CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY)")
            version = conn.execute("SELECT COALESCE(MAX(version), 0) FROM schema_migrations").fetchone()[0]
            for number, script in enumerate(migrations[version:], start=version + 1):
                for statement in script.split(";"):
                    if statement.strip():
                        conn.execute(statement.replace("PRIMARY KEY AUTOINCREMENT", "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"))
                conn.execute("INSERT INTO schema_migrations (version) VALUES (?)", (number,))
    except BaseException:
        conn.close()
        raise
    return conn
